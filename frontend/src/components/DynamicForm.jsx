import { useEffect, useState } from 'react';
import { request } from '../services/api';
import Modal from './Modal';
function inputType(type = '') {
  const t = type.toLowerCase();
  if (['integer','bigint','smallint','numeric','decimal','real','double precision','int','float','double'].includes(t)) return 'number';
  if (t.includes('date') && !t.includes('time')) return 'date';
  if (t.includes('timestamp') || t.includes('datetime')) return 'datetime-local';
  return 'text';
}
export default function DynamicForm({ table, schema, record, onClose, onSaved }) {
  const [values, setValues] = useState({});
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  useEffect(() => {
    const initial = {};
    schema.columns.forEach(c => { if (record) initial[c.name] = record[c.name] == null ? '' : String(record[c.name]); });
    setValues(initial);
  }, [schema, record]);
  async function submit(e) {
    e.preventDefault(); setBusy(true); setError('');
    const payload = {};
    schema.columns.forEach(c => {
      if (c.primaryKey || c.generated) return;
      if (Object.prototype.hasOwnProperty.call(values, c.name)) {
        let value = values[c.name];
        if (c.dataType?.toLowerCase().includes('bool')) value = value === 'true';
        payload[c.name] = value;
      }
    });
    try {
      if (record) await request(`/data/${encodeURIComponent(table)}/${encodeURIComponent(record[schema.primaryKeys[0]])}`, { method: 'PUT', body: JSON.stringify(payload) });
      else await request(`/data/${encodeURIComponent(table)}`, { method: 'POST', body: JSON.stringify(payload) });
      onSaved();
    } catch (err) { setError(err.message); }
    finally { setBusy(false); }
  }
  return <Modal title={record ? 'Edit record' : 'Create record'} onClose={onClose}>
    <form className="dynamic-form" onSubmit={submit}>
      <p className="muted form-intro">Fields are generated from the selected table's database schema.</p>
      {schema.columns.filter(c => !c.generated && !c.primaryKey).map(c => <div className="field" key={c.name}>
        <label>{c.name} {!c.nullable && <span className="required">*</span>} <small>{c.nativeType || c.dataType}</small></label>
        {c.dataType?.toLowerCase().includes('bool')
          ? <select required={!c.nullable} value={values[c.name] ?? ''} onChange={e => setValues(v => ({ ...v, [c.name]: e.target.value }))}><option value="">Select value</option><option value="true">True</option><option value="false">False</option></select>
          : <input type={inputType(c.dataType)} required={!c.nullable} step={inputType(c.dataType) === 'number' ? 'any' : undefined} value={values[c.name] ?? ''} onChange={e => setValues(v => ({ ...v, [c.name]: e.target.value }))} placeholder={c.nullable ? 'Optional' : `Enter ${c.name}`}/>}
        {c.foreignKey && <small className="field-hint">References {c.foreignKey.table}.{c.foreignKey.referencedColumn}</small>}
      </div>)}
      {schema.columns.filter(c => c.primaryKey).map(c => <div className="field" key={c.name}><label>{c.name} <small>Primary key · database generated or read-only</small></label><input disabled value={record?.[c.name] ?? 'Generated by database'}/></div>)}
      {error && <div className="alert error">{error}</div>}
      <div className="modal-actions"><button type="button" className="secondary-btn" onClick={onClose}>Cancel</button><button className="primary-btn" disabled={busy}>{busy ? 'Saving…' : 'Save record'}</button></div>
    </form>
  </Modal>;
}